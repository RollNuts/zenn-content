CORE_PIN = '9b5429aac861164cc1b41278dcaf540fa6fabad7'
COMMAND = 'perform_request'
RESOURCE = 'tauri_command::' + COMMAND
SEED = 'src-tauri/src/cmd.rs'
PERMISSION_FILE = 'src-tauri/permissions/autogenerated/perform_request.toml'
