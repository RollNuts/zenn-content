class ComparisonError(RuntimeError):
    """Bounded errors prevent subprocess output or local paths being published."""


def executable(name: str) -> str:
    result = shutil.which(name)
    if not result:
        raise ComparisonError('Required executable is unavailable.')
    return result


def run_command(arguments: list[str], *, cwd: Path | None = None,
                environment: dict | None = None, allow_no_match: bool = False) -> str:
    try:
        result = subprocess.run(arguments, cwd=cwd, env=environment,
                                stdin=subprocess.DEVNULL, capture_output=True,
                                text=True, timeout=30, check=False)
    except (OSError, subprocess.SubprocessError):
        raise ComparisonError('Local command could not complete.') from None
    if result.returncode not in ((0, 1) if allow_no_match else (0,)):
        raise ComparisonError('Local command failed.')
    return result.stdout


def source_git_environment(base: dict | None = None) -> dict:
    environment = {key: value for key, value in (os.environ if base is None else base).items()
                   if not key.startswith('GIT_')}
    environment.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull,
                       GIT_OPTIONAL_LOCKS='0', GIT_TERMINAL_PROMPT='0',
                       GIT_ATTR_NOSYSTEM='1', GIT_NO_REPLACE_OBJECTS='1',
                       GIT_NO_LAZY_FETCH='1')
    return environment


def source_git_prefix(root: Path, git_binary: str) -> list[str]:
    return [git_binary, '-c', 'protocol.allow=never', '-c', 'core.fsmonitor=false',
            '-c', 'core.hooksPath=' + os.devnull, '-c', 'submodule.recurse=false',
            '-c', 'core.attributesFile=' + os.devnull, '-C', str(root)]


def validate_source(root: Path, git_binary: str) -> dict:
    """Check the complete analysis subtree without status or Git clean filters.

    Git status can hide index-flagged changes and invoke local helpers. Read
    index/tree metadata instead, then hash every raw working file as a Git blob.
    A sparse checkout outside examples/api is permitted; this entire input
    subtree must be materialized and byte-identical to the pinned Git tree.
    """
    root = root.resolve(strict=True)
    environment = source_git_environment()
    prefix = source_git_prefix(root, git_binary)
    def git(*args, allow_missing=False):
        return run_command(prefix + list(args), environment=environment,
                           allow_no_match=allow_missing).rstrip('\n')
    if Path(git('rev-parse', '--show-toplevel')).resolve() != root:
        raise ComparisonError('Source path must be the repository root.')
    if git('rev-parse', 'HEAD') != TAURI_PIN:
        raise ComparisonError('Source checkout differs from the fixed Tauri pin.')
    for entry in git('ls-files', '-v', '-z', '--', 'examples/api').split('\0'):
        if not entry:
            continue
        if len(entry) < 3 or entry[1] != ' ' or entry[0] == 'S' or entry[0].islower():
            raise ComparisonError('Source subtree has hidden or unsupported index state.')
    expected = {}
    for entry in git('ls-tree', '-r', '-l', '-z', '--full-tree', TAURI_PIN,
                     '--', 'examples/api').split('\0'):
        if not entry:
            continue
        metadata, separator, path = entry.partition('\t')
        fields = metadata.split()
        if (not separator or len(fields) != 4 or fields[0] not in {'100644', '100755'}
                or fields[1] != 'blob' or re.fullmatch(r'[0-9a-f]{40}', fields[2]) is None
                or not fields[3].isdigit() or not relative_path(path)
                or not path.startswith('examples/api/') or path in expected):
            raise ComparisonError('Fixed source tree has unsupported entries.')
        expected[path] = (fields[0], fields[2], int(fields[3]))
    if not expected:
        raise ComparisonError('Fixed source subtree is unavailable.')
    indexed = {}
    for entry in git('ls-files', '--stage', '-z', '--', 'examples/api').split('\0'):
        if not entry:
            continue
        metadata, separator, path = entry.partition('\t')
        fields = metadata.split()
        if not separator or len(fields) != 3 or fields[2] != '0' or path in indexed:
            raise ComparisonError('Source index has unsupported entries.')
        indexed[path] = (fields[0], fields[1])
    if indexed != {path: fields[:2] for path, fields in expected.items()}:
        raise ComparisonError('Source index differs from the fixed subtree.')
    allowed_dirs = {str(parent) for path in expected for parent in Path(path).parents
                    if str(parent).startswith('examples/api')}
    observed = set()
    api = root / 'examples/api'
    if api.is_symlink() or not api.is_dir() or (root / 'examples').is_symlink():
        raise ComparisonError('Source subtree must be an ordinary directory.')
    def walk_error(_error):
        raise ComparisonError('Source subtree could not be enumerated.')
    for directory, dirs, files in os.walk(api, followlinks=False, onerror=walk_error):
        for name in dirs:
            path = Path(directory) / name
            if path.is_symlink() or path.relative_to(root).as_posix() not in allowed_dirs:
                raise ComparisonError('Source subtree has an unexpected directory.')
        for name in files:
            path = Path(directory) / name
            relative = path.relative_to(root).as_posix()
            if relative not in expected:
                raise ComparisonError('Source subtree has an untracked or ignored file.')
            observed.add(relative)
            before = path.lstat()
            if not stat.S_ISREG(before.st_mode) or before.st_size != expected[relative][2]:
                raise ComparisonError('Source file differs from the fixed blob.')
            descriptor = os.open(path, os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0))
            with os.fdopen(descriptor, 'rb') as stream:
                opened = os.fstat(stream.fileno())
                if (opened.st_dev, opened.st_ino, opened.st_size) != (before.st_dev, before.st_ino, before.st_size):
                    raise ComparisonError('Source file changed while opening it.')
                digest = hashlib.sha1(b'blob ' + str(opened.st_size).encode() + b'\0', usedforsecurity=False)
                for block in iter(lambda: stream.read(65536), b''):
                    digest.update(block)
                if digest.hexdigest() != expected[relative][1]:
                    raise ComparisonError('Source bytes differ from the fixed blob.')
    if observed != set(expected):
        raise ComparisonError('Source subtree is incomplete.')
    return {'repository': 'https://github.com/tauri-apps/tauri', 'commit': TAURI_PIN,
            'analysis_root': 'examples/api',
            'api_tree': git('rev-parse', TAURI_PIN + ':examples/api')}


def checklist_evidence(api: Path) -> list[dict]:
    result = []
    for path, role, first, last, fragment in CHECKLIST:
        lines = (api / path).read_text(encoding='utf-8').splitlines()
        if not any(fragment in line for line in lines[first - 1:last]):
            raise ComparisonError('Fixed source evidence no longer matches its declared lines.')
        result.append({'path': path, 'role': role,
                       'line_start': first, 'line_end': last,
                       'evidence_url': URL_PREFIX + path + f'#L{first}-L{last}'})
    return result


def parse_search(output: str) -> dict:
    hits = []
    seed_lines = []
    for line in output.splitlines():
        parts = line.split(':', 2)
        if len(parts) != 3:
            raise ComparisonError('Search output format is unsupported.')
        path = parts[0].removeprefix('./')
        if not relative_path(path) or not parts[1].isdigit():
            raise ComparisonError('Search did not return relative path/line evidence.')
        number = int(parts[1])
        if number < 1:
            raise ComparisonError('Search returned an invalid line number.')
        if path == SEED:
            seed_lines.append(number)
            continue
        hits.append({'path': path, 'line': number,
                     'evidence_url': URL_PREFIX + path + f'#L{number}'})
    hits.sort(key=lambda hit: (hit['path'], hit['line']))
    return {'candidates': sorted({hit['path'] for hit in hits}),
            'hits': hits, 'excluded_seed_lines': sorted(set(seed_lines))}


def follow_allow_identifier(api: Path, literal_candidates: list[str]) -> dict | None:
    # Follow only a file actually exposed by the first search, rather than using
    # the independent checklist to feed the baseline its next answer.
    if PERMISSION_FILE not in literal_candidates:
        return None
    body = (api / PERMISSION_FILE).read_text(encoding='utf-8')
    permissions = tomllib.loads(body).get('permission', [])
    identifiers = [item.get('identifier') for item in permissions
                   if COMMAND in item.get('commands', {}).get('allow', [])]
    if len(identifiers) != 1 or not isinstance(identifiers[0], str):
        raise ComparisonError('The discovered allow mapping is ambiguous.')
    identifier = identifiers[0]
    if re.fullmatch(r'allow-[a-z0-9-]+', identifier) is None:
        raise ComparisonError('The discovered allow identifier is unsupported.')
    lines = [number for number, line in enumerate(body.splitlines(), 1)
             if re.fullmatch(r'identifier\s*=\s*"' + re.escape(identifier) + r'"\s*', line)]
    if len(lines) != 1:
        raise ComparisonError('The allow identifier has no unique line evidence.')
    return {'path': PERMISSION_FILE, 'identifier': identifier, 'identifier_line': lines[0],
            'evidence_url': URL_PREFIX + PERMISSION_FILE + f'#L{lines[0]}',
            'source_file_context_reads': 1}


def literal_search(api: Path, rg_binary: str, query: str) -> dict:
    arguments = [rg_binary, '--no-config', '--no-heading', '--color', 'never',
                 '-n', '-F', '--', query, '.']
    return parse_search(run_command(arguments, cwd=api, allow_no_match=True))


def assess(candidates: list[str], checklist: list[dict]) -> dict:
    expected = {row['path'] for row in checklist}
    actual = set(candidates)
    return {'included_checklist_paths': sorted(actual & expected),
            'not_included_checklist_paths': sorted(expected - actual),
            'outside_known_checklist_paths': sorted(actual - expected),
            'scope': 'Selected inspect-checklist only; outside paths are unassessed, not labelled false positives.'}


def project_mcp(result: dict, queries: SnapshotQueries) -> dict:
    if (set(result['tools']) != {'graph_summary', 'tauri_related_files'}
            or result['summary'] != queries.summary()
            or result['related'] != queries.related_files(SEED)):
        raise ComparisonError('Actual MCP results differed from the selected fixed snapshot.')
    related = result['related']
    rows = [{key: row[key] for key in (
        'resource', 'related_file', 'target_role', 'peer_role',
        'target_reference_status', 'peer_reference_status',
        'peer_analysis_status', 'evidence_status')}
        for row in related['relations'] if row['resource'] == RESOURCE]
    protocol = result['protocol_version']
    if not isinstance(protocol, str) or re.fullmatch(r'\d{4}-\d{2}-\d{2}', protocol) is None:
        raise ComparisonError('Unexpected SDK protocol identifier.')
    return {
        'transport': 'real SDK stdio subprocess', 'protocol_version': protocol,
        'stdio_sessions': 1, 'tools_list_calls': 1, 'tool_calls': 2,
        'calls': [{'tool': 'graph_summary', 'arguments': {}},
                  {'tool': 'tauri_related_files', 'arguments': {'path': SEED}}],
        'query_status': related['status'], 'total_relation_rows': related['total_relation_rows'],
        'returned_relation_rows': len(related['relations']), 'truncated': related['truncated'],
        'matched_command_rows': rows,
        'excluded_other_command_rows': len(related['relations']) - len(rows),
        'candidates': sorted({row['related_file'] for row in rows}),
        'current_worktree_verified': related['snapshot']['current_worktree_verified'],
        'current_state_or_merge_safety_proven': related['current_state_or_merge_safety_proven'],
        'analysis_coverage': {key: result['summary'][key] for key in (
            'files_parsed', 'files_failed', 'files_skipped', 'document_count',
            'analysis_status_counts', 'tauri_command_count', 'retained_contract_edge_count')},
    }


def compare(tauri: Path, snapshot: Path, git_binary: str, rg_binary: str) -> tuple[dict, dict]:
    tauri = tauri.resolve()
    source = validate_source(tauri, git_binary)
    api = tauri / 'examples/api'
    checklist = checklist_evidence(api)
    queries = SnapshotQueries(snapshot)
    if queries.snapshot['core_commit'] != CORE_PIN:
        raise ComparisonError('Snapshot differs from the fixed Core pin.')
    git_version = run_command([git_binary, '--version']).splitlines()[0]
    rg_version = run_command([rg_binary, '--version']).splitlines()[0]
    if (not re.fullmatch(r'git version [0-9A-Za-z. ()_-]+', git_version)
            or not re.fullmatch(r'ripgrep [0-9.]+(?: \(rev [0-9a-f]+\))?', rg_version)):
        raise ComparisonError('Unsupported executable version output.')
    versions = {'python': platform.python_version(), 'mcp_sdk': version('mcp'),
                'git': git_version, 'ripgrep': rg_version}
    started = time.perf_counter()
    literal = literal_search(api, rg_binary, COMMAND)
    literal_seconds = time.perf_counter() - started
    started = time.perf_counter()
    followed = follow_allow_identifier(api, literal['candidates'])
    context_seconds = time.perf_counter() - started
    trace, trace_seconds = None, None
    if followed:
        started = time.perf_counter()
        trace = literal_search(api, rg_binary, followed['identifier'])
        trace_seconds = time.perf_counter() - started
    expanded = sorted(set(literal['candidates']) | set(trace['candidates'] if trace else []))
    from client_demo import call
    started = time.perf_counter()
    result = asyncio.run(call(snapshot, SEED))
    mcp_seconds = time.perf_counter() - started
    c = project_mcp(result, queries)
    a = {'search_root': 'examples/api', 'standard_ignore_rules': True,
         'rg_process_calls': 2 if trace is not None else 1,
         'source_file_context_reads': 1 if followed else 0,
         'literal': {'query': COMMAND, **literal,
                     'checklist': assess(literal['candidates'], checklist)},
         'permission_identifier_followup': followed,
         'trace_query': followed['identifier'] if followed else None,
         'trace_search': trace, 'trace_expanded_candidates': expanded,
         'trace_expanded_checklist': assess(expanded, checklist)}
    c['checklist'] = assess(c['candidates'], checklist)
    report = {
        'comparison': 'perform-request-search-vs-core-mcp-v1', 'versions': versions,
        'question': 'Which peer files should be inspected before renaming perform_request?',
        'inputs': {'source': source, 'core_commit': CORE_PIN, 'seed': SEED,
                   'resource': RESOURCE, 'snapshot_sha256': queries.snapshot['snapshot_sha256'],
                   'snapshot_source_commit_embedded': False},
        'known_inspect_checklist': checklist,
        'checklist_provenance': 'AI-assisted source inspection and separate AI review, before this comparison; not exhaustive independent ground truth.',
        'A_string_search': a,
        'B_ordinary_AI': {'status': 'not_run_in_this_experiment',
                          'prior_codex_success_is_C_side_only_not_a_baseline': True},
        'C_core_mcp': c,
        'limitations': [
            'This one fixed command/checklist measures no general precision, recall, productivity or time saved.',
            'Checklist peers are inspection locations, not a claim that all require edits; generated TOML must not be hand-edited.',
            'The snapshot has no embedded Tauri source SHA; its exact bytes and the separately checked source tree are identified.',
            'C queries a prepared snapshot. Core extraction cost is not included in the measured query time.',
            'A follows an identifier found in a literal-search result; literal and trace-expanded candidate sets are reported separately.',
            'MCP metadata and incomplete/uncertain evidence do not prove current state, runtime correctness or rename safety.',
            'B was not run here. Existing Codex-with-MCP records do not establish a normal-AI baseline.',
        ],
    }
    timings = {'units': 'seconds',
               'meaning': 'Machine elapsed execution only; excludes setup, source-checklist inspection, Core extraction and human review.',
               'A_literal_rg': literal_seconds, 'A_permission_context_read': context_seconds,
               'A_trace_rg': trace_seconds, 'C_stdio_session_and_two_tools': mcp_seconds,
               'not_measured': ['Human investigation time', 'Core snapshot extraction', 'Ordinary AI B']}
    if validate_source(tauri, git_binary) != source:
        raise ComparisonError('Source identity changed during the comparison.')
    return report, timings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tauri', type=Path, required=True)
    parser.add_argument('--snapshot', type=Path, required=True)
    parser.add_argument('--git', default=shutil.which('git') or 'git')
    parser.add_argument('--rg', default=shutil.which('rg') or 'rg')
    parser.add_argument('--timings', type=Path)
    args = parser.parse_args(argv)
    try:
        if args.timings and (args.timings.resolve().is_relative_to(args.tauri.resolve())
                             or args.timings.resolve() == args.snapshot.resolve()):
            raise ComparisonError('Timing output must not overwrite an input.')
        report, timings = compare(args.tauri, args.snapshot,
                                  executable(args.git), executable(args.rg))
        if args.timings:
            args.timings.write_text(json.dumps(timings, indent=2) + '\n', encoding='utf-8')
    except Exception:
        # SDK transport errors can be exception groups containing local paths.
        # CLI failure is bounded; raw subprocess/SDK diagnostics are not copied.
        print('Comparison failed; check fixed public source, snapshot and local dependencies. '
              'No successful result is claimed.', file=sys.stderr)
        return 1
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
