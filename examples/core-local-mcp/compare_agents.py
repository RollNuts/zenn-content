class HarnessError(RuntimeError):
    pass


def private_write(path: Path, data: str | bytes) -> None:
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, 'wb') as stream:
        stream.write(data.encode('utf-8') if isinstance(data, str) else data)


def child_environment() -> dict[str, str]:
    # Preserve CODEX_HOME for existing auth; never repurpose it. Remove API-key
    # providers/overrides so a model task cannot fall back to an environment key.
    return {key: value for key, value in os.environ.items()
            if 'API_KEY' not in key.upper() and not key.startswith(('OPENAI_', 'AZURE_OPENAI_'))
            and key not in {'CODEX_TOKEN', 'CODEX_MODEL'} and not key.startswith('GIT_')}


def local_command(arguments: list[str], environment: dict) -> str:
    try:
        result = subprocess.run(arguments, stdin=subprocess.DEVNULL, capture_output=True,
                                text=True, env=environment, timeout=15, check=False)
    except (OSError, subprocess.SubprocessError):
        raise HarnessError('Local preflight command could not complete.') from None
    if result.returncode:
        raise HarnessError('Local preflight command failed.')
    return result.stdout.strip()


def preflight(args, environment: dict) -> dict:
    cli_version = local_command([str(args.codex), '--version'], environment)
    if cli_version != 'codex-cli 0.167.0':
        raise HarnessError('This comparison is pinned to CLI 0.167.0.')
    help_text = local_command([str(args.codex), 'exec', '--help'], environment)
    flags = ('--ignore-user-config', '--ephemeral', '--skip-git-repo-check', '--sandbox',
             '--json', '--output-schema', '--output-last-message', '--cd', '--config')
    if not all(flag in help_text for flag in flags):
        raise HarnessError('CLI help does not expose every required exec flag.')
    if not args.server.is_file() or not args.snapshot.is_file():
        raise HarnessError('Existing local MCP assets are unavailable.')
    envelope = json.loads(args.snapshot.read_text(encoding='utf-8'))
    if (envelope.get('core_commit') != CORE_PIN
            or envelope.get('format') != 'veripsa-local-mcp-demo-v1'):
        raise HarnessError('Snapshot identity differs from the fixed experiment.')
    sdk = json.loads(local_command([
        str(args.sdk_python), '-B', '-c',
        'import json,sys; from importlib.metadata import version; '
        'print(json.dumps({"python":sys.version.split()[0],"mcp":version("mcp")}))',
    ], environment))
    return {'codex_cli': cli_version, 'exec_flags_checked_against_help': True,
            'sdk': sdk, 'model_requested': 'CLI default, no model override',
            'snapshot_sha256': hashlib.sha256(args.snapshot.read_bytes()).hexdigest()}


def archive_api(args, environment: dict) -> bytes:
    git_env = dict(environment)
    git_env.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull,
                   GIT_OPTIONAL_LOCKS='0', GIT_TERMINAL_PROMPT='0', GIT_NO_LAZY_FETCH='1',
                   GIT_NO_REPLACE_OBJECTS='1')
    prefix = [str(args.git), '-c', 'protocol.allow=never', '-C', str(args.tauri)]
    if local_command(prefix + ['rev-parse', '--verify', TAURI_PIN + '^{commit}'], git_env) != TAURI_PIN:
        raise HarnessError('Fixed Tauri commit is unavailable locally.')
    try:
        result = subprocess.run(prefix + ['archive', '--format=tar', TAURI_PIN + ':examples/api'],
                                stdin=subprocess.DEVNULL, capture_output=True, env=git_env,
                                timeout=30, check=False)
    except (OSError, subprocess.SubprocessError):
        raise HarnessError('Local archive could not complete.') from None
    if result.returncode or not result.stdout:
        raise HarnessError('Local archive failed.')
    return result.stdout


def extract_api(data: bytes, destination: Path) -> None:
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:') as archive:
        members = archive.getmembers()
        seen = set()
        for member in members:
            path = PurePosixPath(member.name)
            if (not path.parts or path.is_absolute() or '..' in path.parts
                    or '\\' in member.name or str(path) in seen
                    or not (member.isdir() or member.isfile())):
                raise HarnessError('Unsafe archive entry.')
            seen.add(str(path))
        destination.mkdir()
        for member in members:
            path = destination.joinpath(*PurePosixPath(member.name).parts)
            if member.isdir():
                path.mkdir(parents=True, exist_ok=True)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                source = archive.extractfile(member)
                if source is None:
                    raise HarnessError('Archive file is unavailable.')
                with source, path.open('xb') as output:
                    shutil.copyfileobj(source, output)


def command(args, method: str, workspace: Path, schema: Path, answer: Path) -> list[str]:
    result = [str(args.codex), 'exec', '--ignore-user-config', '--ephemeral',
              '--skip-git-repo-check', '--sandbox', 'read-only', '--cd', str(workspace),
              '--json', '--color', 'never', '--output-schema', str(schema),
              '--output-last-message', str(answer), '-c', 'approval_policy="never"',
              '-c', 'forced_login_method="chatgpt"', '-c', 'web_search="disabled"']
    if method == 'C':
        result += ['-c', 'mcp_servers.core_contracts.command=' + json.dumps(str(args.sdk_python)),
                   '-c', 'mcp_servers.core_contracts.args=' + json.dumps([
                       '-B', str(args.server), '--snapshot', str(args.snapshot)]),
                   '-c', 'mcp_servers.core_contracts.enabled_tools=["graph_summary","tauri_related_files"]',
                   '-c', 'mcp_servers.core_contracts.required=true']
    return result + [PROMPT]


def relative_path(value) -> bool:
    return (isinstance(value, str) and bool(value) and len(value) <= 1024
            and not value.startswith('/') and '\\' not in value and ':' not in value
            and not any(ord(c) < 32 for c in value)
            and all(part not in ('', '.', '..') for part in value.split('/')))


def public_answer(data: dict) -> dict:
    if not isinstance(data, dict) or set(data) != set(SCHEMA['required']):
        raise HarnessError('Final answer does not match the declared schema.')
    if (type(data['claims_complete']) is not bool or type(data['merge_safety_proven']) is not bool
            or not isinstance(data['peers'], list) or len(data['peers']) > 100
            or not isinstance(data['uncertainty_notes'], list) or len(data['uncertainty_notes']) > 50):
        raise HarnessError('Invalid final-answer fields.')
    paths = set()
    for peer in data['peers']:
        if (not isinstance(peer, dict) or set(peer) != {'path', 'reason'}
                or not relative_path(peer['path']) or peer['path'] == SEED
                or peer['path'] in paths or not isinstance(peer['reason'], str)
                or not 1 <= len(peer['reason']) <= 2000):
            raise HarnessError('Invalid peer answer.')
        paths.add(peer['path'])
    if any(not isinstance(note, str) or not 1 <= len(note) <= 4000
           for note in data['uncertainty_notes']):
        raise HarnessError('Invalid uncertainty note.')
    encoded = json.dumps(data)
    if any(fragment in encoded for fragment in ('/Users/', '/private/', '/var/folders/', '/tmp/',
                                                'sk-proj-', 'sk-live-', 'Bearer ')):
        raise HarnessError('Potential private data in the proposed receipt.')
    return data


def tool_receipt(events: list[dict]) -> dict:
    completed = [event['item'] for event in events if event.get('type') == 'item.completed'
                 and isinstance(event.get('item'), dict)]
    tools = [item for item in completed if item.get('type') not in {'reasoning', 'agent_message'}]
    counts = Counter(item.get('type') for item in tools)
    if any(not isinstance(key, str) or re.fullmatch(r'[a-z_]{1,80}', key) is None for key in counts):
        raise HarnessError('Unexpected tool-event type.')
    model_values = {event[key] for event in events
                    if event.get('type') in {'thread.started', 'turn.started', 'session.started'}
                    for key in ('model', 'model_slug') if isinstance(event.get(key), str)
                    and re.fullmatch(r'[a-zA-Z0-9_.:/-]{1,100}', event[key])}
    model = next(iter(model_values)) if len(model_values) == 1 else None
    model_resolved = model is not None and model not in {'default', 'auto'}
    return {'event_tool_counts': dict(sorted(counts.items())),
            'resolved_model': model if model_resolved else None,
            'resolved_model_observed': model_resolved,
            'failed_turn_event': any(event.get('type') in {'error', 'turn.failed'} for event in events),
            'unexpected_or_non_source_tool_events': sum(
                count for kind, count in counts.items() if kind not in {'command_execution', 'mcp_tool_call'}),
            'tool_sequence': [item['type'] for item in tools],
            'core_calls': [{'tool': item.get('tool'), 'status': item.get('status'),
                            'error_present': item.get('error') is not None}
                           for item in tools if item.get('type') == 'mcp_tool_call'
                           and item.get('server') == 'core_contracts'
                           and item.get('tool') in {'graph_summary', 'tauri_related_files'}],
            'unexpected_mcp_call_count': sum(
                item.get('type') == 'mcp_tool_call' and not (
                    item.get('server') == 'core_contracts'
                    and item.get('tool') in {'graph_summary', 'tauri_related_files'}) for item in tools)}


def mcp_answers(events: list[dict], queries) -> list[dict]:
    result = []
    for event in events:
        item = event.get('item')
        if not (event.get('type') == 'item.completed' and isinstance(item, dict)
                and item.get('type') == 'mcp_tool_call' and item.get('server') == 'core_contracts'
                and item.get('tool') in {'graph_summary', 'tauri_related_files'}):
            continue
        tool, arguments = item['tool'], item.get('arguments')
        if tool == 'graph_summary' and arguments == {}:
            expected = queries.summary()
        elif (tool == 'tauri_related_files' and isinstance(arguments, dict)
              and not set(arguments) - {'path', 'limit'} and arguments.get('path') == SEED):
            expected = queries.related_files(SEED, arguments.get('limit', 20))
        else:
            result.append({'tool': tool, 'arguments_verified': False})
            continue
        raw = item.get('result')
        actual = raw.get('structured_content') if isinstance(raw, dict) else None
        if actual is None and isinstance(raw, dict):
            content = raw.get('content')
            if isinstance(content, list) and content and isinstance(content[0], dict):
                try:
                    actual = json.loads(content[0].get('text', ''))
                except (TypeError, ValueError):
                    pass
        verified = (item.get('status') == 'completed' and item.get('error') is None
                    and actual == expected)
        row = {'tool': tool, 'arguments_verified': True, 'snapshot_result_verified': verified}
        if verified and tool == 'graph_summary':
            row['answer'] = {key: expected[key] for key in (
                'files_parsed', 'files_failed', 'files_skipped', 'document_count',
                'analysis_status_counts', 'tauri_command_count', 'retained_contract_edge_count')}
        elif verified:
            row['answer'] = {key: expected[key] for key in (
                'path', 'status', 'total_relation_rows', 'truncated', 'relations',
                'current_state_or_merge_safety_proven')}
        result.append(row)
    return result


def run_trial(args, method: str, workspace: Path, private: Path, schema: Path,
              environment: dict, queries) -> dict:
    stdout, stderr, answer = (private / f'{method}.{suffix}' for suffix in
                              ('stdout.jsonl', 'stderr.log', 'answer.json'))
    private_write(stdout, b'')
    private_write(stderr, b'')
    started = time.perf_counter()
    timed_out = False
    with stdout.open('ab') as output, stderr.open('ab') as errors:
        process = subprocess.Popen(command(args, method, workspace, schema, answer),
                                   stdin=subprocess.DEVNULL, stdout=output, stderr=errors,
                                   env=environment, start_new_session=True)
        try:
            process.wait(timeout=120)
        except subprocess.TimeoutExpired:
            timed_out = True
            os.killpg(process.pid, signal.SIGTERM)
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait(timeout=5)
        except BaseException:
            # An interrupted parent must not leave a model/MCP process running.
            if process.poll() is None:
                try:
                    os.killpg(process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
                process.wait(timeout=5)
            raise
    elapsed = time.perf_counter() - started
    if answer.exists():
        answer.chmod(0o600)
    receipt = {'method': method, 'attempts': 1, 'timeout_seconds': 120,
               'timed_out': timed_out, 'process_exit_code': process.returncode,
               'elapsed_seconds': elapsed,
               'clock_scope': 'CLI wall time including any queue/API/tool time and timeout cleanup; not human time.'}
    if stdout.stat().st_size > 20 * 1024 * 1024:
        receipt['result_status'] = 'unparsed_large_private_log'
        return receipt
    try:
        events = [json.loads(line) for line in stdout.read_text(encoding='utf-8').splitlines() if line.strip()]
        if any(not isinstance(event, dict) for event in events):
            raise HarnessError('Unexpected event envelope.')
        receipt.update(tool_receipt(events))
        receipt['mcp_query_answers'] = mcp_answers(events, queries)
        if method == 'C':
            prerequisite = (
                receipt['tool_sequence'][:2] == ['mcp_tool_call', 'mcp_tool_call']
                and [row['tool'] for row in receipt['core_calls'][:2]]
                == ['graph_summary', 'tauri_related_files']
                and len(receipt['mcp_query_answers']) >= 2
                and all(row.get('snapshot_result_verified')
                        for row in receipt['mcp_query_answers']))
        else:
            prerequisite = receipt['event_tool_counts'].get('mcp_tool_call', 0) == 0
        receipt['tooling_conditions_observed'] = (
            prerequisite and receipt['unexpected_mcp_call_count'] == 0
            and receipt['unexpected_or_non_source_tool_events'] == 0)
        if process.returncode == 0 and not timed_out and not receipt['failed_turn_event']:
            data = public_answer(json.loads(answer.read_text(encoding='utf-8')))
            peers = {row['path'] for row in data['peers']}
            receipt.update(result_status='answer_observed', answer=data,
                           unsupported_completeness_or_safety_claim=(
                               data['claims_complete'] or data['merge_safety_proven']),
                           peer_source_presence=[{'path': row['path'],
                                                  'exists': (workspace / row['path']).is_file()}
                                                 for row in data['peers']],
                           checklist_included=sorted(peers & CHECKLIST),
                           checklist_not_included=sorted(CHECKLIST - peers),
                           outside_known_checklist_unassessed=sorted(peers - CHECKLIST))
        else:
            receipt['result_status'] = 'trial_failed_or_timed_out'
    except Exception:
        receipt['result_status'] = 'unparsed_or_unpublishable_answer'
    return receipt


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', action='store_true', help='Execute exactly one B and one C; otherwise preflight only')
    parser.add_argument('--codex', type=Path, required=True)
    parser.add_argument('--tauri', type=Path, required=True)
    parser.add_argument('--sdk-python', type=Path, default=Path(sys.executable).absolute())
    parser.add_argument('--server', type=Path, default=HERE / 'server.py')
    parser.add_argument('--snapshot', type=Path, required=True)
    parser.add_argument('--git', type=Path, required=True)
    parser.add_argument('--private-dir', type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        if os.name != 'posix':
            raise HarnessError('This comparison requires POSIX process groups.')
        # Preserve the venv interpreter symlink: resolving it would lose its SDK environment.
        for key in ('codex', 'tauri', 'sdk_python', 'server', 'snapshot', 'git', 'private_dir'):
            setattr(args, key, getattr(args, key).absolute())
        environment = child_environment()
        metadata = preflight(args, environment)
        if not args.run:
            print(json.dumps({**metadata, 'run_requested': False, 'model_calls_started': 0}, indent=2))
            return 0
        private = args.private_dir.resolve()
        if private.exists() or any((ancestor / '.git').exists() for ancestor in (private, *private.parents)):
            raise HarnessError('Private output must be a new directory outside every Git worktree.')
        archive = archive_api(args, environment)
        sys.path.insert(0, str(args.server.parent))
        from query_service import SnapshotQueries
        queries = SnapshotQueries(args.snapshot)
        private.mkdir(mode=0o700)
        schema = private / 'answer-schema.json'
        private_write(schema, json.dumps(SCHEMA))
        private_write(private / 'common-prompt.txt', PROMPT)
        trials = []
        for method in ('B', 'C'):
            with tempfile.TemporaryDirectory(prefix='workspace-' + method + '-', dir=private) as directory:
                workspace = Path(directory) / method
                extract_api(archive, workspace)
                receipt = run_trial(args, method, workspace, private, schema, environment, queries)
                private_write(private / f'{method}.receipt.json', json.dumps(receipt, indent=2))
                trials.append(receipt)
        report = {**metadata, 'experiment': 'agent-b-c-single-shot-v1',
                  'source_commit': TAURI_PIN, 'analysis_root': 'examples/api',
                  'same_archive_sha256': hashlib.sha256(archive).hexdigest(),
                  'prompt_sha256': hashlib.sha256(PROMPT.encode()).hexdigest(),
                  'authentication_requested': 'Existing ChatGPT credentials only; API-key environment removed.',
                  'tool_difference': 'B ordinary source tools; C same source tools plus required core_contracts MCP.',
                  'trial_order': ['B', 'C'], 'trials': trials,
                  'limitations': [
                      'Two single trials, fixed B-then-C order, no retries or counterbalancing; no general model-quality claim.',
                      'Same CLI default requested; a resolved model is reported only if event metadata exposes it.',
                      'Wall time includes queue/API/tool work, not human review; SDK-only and string-search results are separate experiments.',
                      'The common prompt conditionally requires MCP first, so instructions and tool availability both affect C.',
                      'Checklist is for scoring only and is not exhaustive independent ground truth; extra paths are unassessed.',
                      'Read-only mode and the prompt are not proof of total filesystem-read isolation or arbitrary shell compliance.',
                      'No application build/test/import is requested; private raw command logs still require human inspection.',
                  ]}
        private_write(private / 'allowlist-receipt.json', json.dumps(report, ensure_ascii=False, indent=2))
        print(json.dumps({'run_finished': True, 'trials': [
            {'method': row['method'], 'result_status': row['result_status']} for row in trials]}, indent=2))
        return 0
    except Exception:
        print('Agent comparison failed. Inspect private local files; no successful comparison is claimed.', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
